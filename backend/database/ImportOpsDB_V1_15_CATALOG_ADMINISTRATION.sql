USE [ImportOpsDB];
GO
SET XACT_ABORT ON;
BEGIN TRANSACTION;

IF NOT EXISTS (SELECT 1 FROM sec.PERMISSION WHERE code = 'CONFIGURATION.VIEW')
    INSERT INTO sec.PERMISSION(code, name, module_code, is_active) VALUES ('CONFIGURATION.VIEW', N'Ver configuración funcional', 'CONFIGURATION', 1);
IF NOT EXISTS (SELECT 1 FROM sec.PERMISSION WHERE code = 'CONFIGURATION.MANAGE')
    INSERT INTO sec.PERMISSION(code, name, module_code, is_active) VALUES ('CONFIGURATION.MANAGE', N'Administrar configuración funcional', 'CONFIGURATION', 1);

DECLARE @viewId int=(SELECT permission_id FROM sec.PERMISSION WHERE code='CONFIGURATION.VIEW');
DECLARE @manageId int=(SELECT permission_id FROM sec.PERMISSION WHERE code='CONFIGURATION.MANAGE');
INSERT INTO sec.ROLE_PERMISSION(role_id,permission_id,can_view,can_create,can_update,can_delete,can_approve)
SELECT r.role_id,@viewId,1,0,0,0,0 FROM sec.ROLE r WHERE r.code='ADMIN' AND r.is_active=1
AND NOT EXISTS(SELECT 1 FROM sec.ROLE_PERMISSION rp WHERE rp.role_id=r.role_id AND rp.permission_id=@viewId);
INSERT INTO sec.ROLE_PERMISSION(role_id,permission_id,can_view,can_create,can_update,can_delete,can_approve)
SELECT r.role_id,@manageId,1,1,1,1,0 FROM sec.ROLE r WHERE r.code='ADMIN' AND r.is_active=1
AND NOT EXISTS(SELECT 1 FROM sec.ROLE_PERMISSION rp WHERE rp.role_id=r.role_id AND rp.permission_id=@manageId);

-- Índices de unicidad de código. Se crean solo si no existen duplicados actuales.
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_TRANSPORT_MODE_CODE' AND object_id=OBJECT_ID('cfg.TRANSPORT_MODE'))
AND NOT EXISTS(SELECT code FROM cfg.TRANSPORT_MODE GROUP BY code HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_TRANSPORT_MODE_CODE ON cfg.TRANSPORT_MODE(code);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_PAYMENT_METHOD_CODE' AND object_id=OBJECT_ID('cfg.PAYMENT_METHOD'))
AND NOT EXISTS(SELECT code FROM cfg.PAYMENT_METHOD GROUP BY code HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_PAYMENT_METHOD_CODE ON cfg.PAYMENT_METHOD(code);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_DOCUMENT_TYPE_COMPANY_CODE' AND object_id=OBJECT_ID('cfg.DOCUMENT_TYPE'))
AND NOT EXISTS(SELECT company_id,code FROM cfg.DOCUMENT_TYPE GROUP BY company_id,code HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_DOCUMENT_TYPE_COMPANY_CODE ON cfg.DOCUMENT_TYPE(company_id,code) WHERE company_id IS NOT NULL;
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_EXPENSE_CATEGORY_COMPANY_CODE' AND object_id=OBJECT_ID('cfg.EXPENSE_CATEGORY'))
AND NOT EXISTS(SELECT company_id,code FROM cfg.EXPENSE_CATEGORY GROUP BY company_id,code HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_EXPENSE_CATEGORY_COMPANY_CODE ON cfg.EXPENSE_CATEGORY(company_id,code);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_SERVICE_CATEGORY_COMPANY_CODE' AND object_id=OBJECT_ID('cfg.SERVICE_CATEGORY'))
AND NOT EXISTS(SELECT company_id,code FROM cfg.SERVICE_CATEGORY GROUP BY company_id,code HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_SERVICE_CATEGORY_COMPANY_CODE ON cfg.SERVICE_CATEGORY(company_id,code);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_COUNTRY_NAME' AND object_id=OBJECT_ID('cfg.COUNTRY'))
AND NOT EXISTS(SELECT country_name FROM cfg.COUNTRY GROUP BY country_name HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_COUNTRY_NAME ON cfg.COUNTRY(country_name);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_CURRENCY_NAME' AND object_id=OBJECT_ID('cfg.CURRENCY'))
AND NOT EXISTS(SELECT currency_name FROM cfg.CURRENCY GROUP BY currency_name HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_CURRENCY_NAME ON cfg.CURRENCY(currency_name);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_TRANSPORT_MODE_NAME' AND object_id=OBJECT_ID('cfg.TRANSPORT_MODE'))
AND NOT EXISTS(SELECT name FROM cfg.TRANSPORT_MODE GROUP BY name HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_TRANSPORT_MODE_NAME ON cfg.TRANSPORT_MODE(name);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_PAYMENT_METHOD_NAME' AND object_id=OBJECT_ID('cfg.PAYMENT_METHOD'))
AND NOT EXISTS(SELECT name FROM cfg.PAYMENT_METHOD GROUP BY name HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_PAYMENT_METHOD_NAME ON cfg.PAYMENT_METHOD(name);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_EXPENSE_CATEGORY_COMPANY_NAME' AND object_id=OBJECT_ID('cfg.EXPENSE_CATEGORY'))
AND NOT EXISTS(SELECT company_id,name FROM cfg.EXPENSE_CATEGORY GROUP BY company_id,name HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_EXPENSE_CATEGORY_COMPANY_NAME ON cfg.EXPENSE_CATEGORY(company_id,name);
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='UX_SERVICE_CATEGORY_COMPANY_NAME' AND object_id=OBJECT_ID('cfg.SERVICE_CATEGORY'))
AND NOT EXISTS(SELECT company_id,name FROM cfg.SERVICE_CATEGORY GROUP BY company_id,name HAVING COUNT(*)>1)
    CREATE UNIQUE INDEX UX_SERVICE_CATEGORY_COMPANY_NAME ON cfg.SERVICE_CATEGORY(company_id,name);

IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE name='IX_PORT_ADMIN_FILTER' AND object_id=OBJECT_ID('cfg.PORT'))
    CREATE INDEX IX_PORT_ADMIN_FILTER ON cfg.PORT(country_code,port_type,is_active) INCLUDE(port_code,port_name,city_name);

COMMIT;
GO
