USE ImportOpsDB;
GO
SET XACT_ABORT ON;
GO

IF OBJECT_ID(N'doc.DOCUMENT_OBSERVATION',N'U') IS NULL
BEGIN
 CREATE TABLE doc.DOCUMENT_OBSERVATION(
   document_observation_id BIGINT IDENTITY PRIMARY KEY,
   document_id BIGINT NOT NULL,
   description NVARCHAR(1500) NOT NULL,
   status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
   observed_at DATETIME2(0) NOT NULL DEFAULT SYSUTCDATETIME(),
   observed_by BIGINT NOT NULL,
   resolved_at DATETIME2(0) NULL,
   resolved_by BIGINT NULL,
   resolution_note NVARCHAR(1500) NULL,
   operation_task_id BIGINT NULL,
   row_ver ROWVERSION,
   CONSTRAINT FK_DOC_OBS_DOC FOREIGN KEY(document_id) REFERENCES doc.DOCUMENT(document_id),
   CONSTRAINT FK_DOC_OBS_BY FOREIGN KEY(observed_by) REFERENCES sec.APP_USER(user_id),
   CONSTRAINT FK_DOC_OBS_RES_BY FOREIGN KEY(resolved_by) REFERENCES sec.APP_USER(user_id),
   CONSTRAINT FK_DOC_OBS_TASK FOREIGN KEY(operation_task_id) REFERENCES ops.OPERATION_TASK(operation_task_id),
   CONSTRAINT CK_DOC_OBS_STATUS CHECK(status IN('OPEN','RESOLVED','CANCELLED'))
 );
END;
GO

IF NOT EXISTS(SELECT 1 FROM sys.check_constraints WHERE name=N'CK_DOCUMENT_STATUS_V8')
BEGIN
 ALTER TABLE doc.DOCUMENT DROP CONSTRAINT CK_DOC_STATUS;
 ALTER TABLE doc.DOCUMENT ADD CONSTRAINT CK_DOCUMENT_STATUS_V8 CHECK(document_status IN('PENDING_REVIEW','VALID','OBSERVED','REPLACED','EXPIRED','VOID'));
END;
GO

IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'doc.DOCUMENT') AND name=N'IX_DOCUMENT_OPERATION_TYPE_STATUS')
 CREATE INDEX IX_DOCUMENT_OPERATION_TYPE_STATUS ON doc.DOCUMENT(company_id,operation_id,document_type_id,document_status,version_no DESC) INCLUDE(expiration_date,is_deleted);
GO

IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'doc.DOCUMENT_OBSERVATION') AND name=N'IX_DOC_OBS_OPEN')
 CREATE INDEX IX_DOC_OBS_OPEN ON doc.DOCUMENT_OBSERVATION(document_id,status,observed_at DESC);
GO
